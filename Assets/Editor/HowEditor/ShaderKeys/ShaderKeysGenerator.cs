using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;
using UnityEngine.Rendering;

/// <summary>
/// 扫描项目 Shader（含 ShaderGraph）与设置中列出的额外 Shader，生成 ShaderKeys.cs：
/// <code>
/// ShaderKeys.Lit.ShaderName            // "Universal Render Pipeline/Lit"
/// ShaderKeys.Lit.BaseColor             // ShaderProperty("_BaseColor")
/// ShaderKeys.Lit.Keywords.NORMALMAP    // "_NORMALMAP"
/// </code>
/// 生成结果配合 ShaderManager 使用：ShaderManager.SetColor("Hero", ShaderKeys.Lit.BaseColor, Color.red)。
/// </summary>
public static class ShaderKeysGenerator
{
    public const string ClassName = "ShaderKeys";

    public class ShaderInfo
    {
        public Shader Shader;
        public string AssetPath;
        /// <summary>项目里的 Shader 生成全部关键字；包里的内置 Shader 只生成材质局部关键字（全局的多是管线内部用）</summary>
        public bool IncludeGlobalKeywords;
    }

    #region 收集

    public static List<ShaderInfo> CollectShaders(out List<string> warnings)
    {
        warnings = new List<string>();
        var s = HowFrameSettings.instance;
        var result = new List<ShaderInfo>();
        var seen = new HashSet<string>();

        var dirs = (s.shaderScanDirs ?? new List<string>())
            .Where(d => !string.IsNullOrWhiteSpace(d) && AssetDatabase.IsValidFolder(d.Trim().TrimEnd('/')))
            .Select(d => d.Trim().TrimEnd('/'))
            .ToArray();
        var excludes = (s.shaderExcludeDirs ?? new List<string>())
            .Where(d => !string.IsNullOrWhiteSpace(d))
            .Select(d => d.Trim().Replace('\\', '/').TrimEnd('/') + "/")
            .ToList();
        if (dirs.Length > 0)
        {
            foreach (var guid in AssetDatabase.FindAssets("t:Shader", dirs))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (excludes.Any(e => path.StartsWith(e, StringComparison.OrdinalIgnoreCase))) continue;
                var shader = AssetDatabase.LoadAssetAtPath<Shader>(path);
                if (shader == null || shader.name.StartsWith("Hidden/") || !seen.Add(shader.name)) continue;
                if (ShaderUtil.ShaderHasError(shader))
                {
                    warnings.Add($"{shader.name} 有编译错误，已跳过（{path}）");
                    continue;
                }
                result.Add(new ShaderInfo { Shader = shader, AssetPath = path, IncludeGlobalKeywords = true });
            }
        }

        foreach (var name in s.shaderExtraNames ?? new List<string>())
        {
            if (string.IsNullOrWhiteSpace(name) || !seen.Add(name.Trim())) continue;
            var shader = Shader.Find(name.Trim());
            if (shader == null)
            {
                warnings.Add($"找不到 Shader: {name}");
                continue;
            }
            result.Add(new ShaderInfo { Shader = shader, AssetPath = AssetDatabase.GetAssetPath(shader), IncludeGlobalKeywords = false });
        }

        return result.OrderBy(i => i.Shader.name, StringComparer.Ordinal).ToList();
    }

    #endregion

    #region 生成

    public static string GenerateCode(IList<ShaderInfo> shaders, string ns)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// 由 Tools/HowFrame/Shader Keys Generator 生成，请勿手改；Shader 改动后重新生成即可。");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine($"namespace {ns}");
        sb.AppendLine("{");
        sb.AppendLine($"    public static class {ClassName}");
        sb.AppendLine("    {");

        var classNames = AssignClassNames(shaders.Select(i => i.Shader.name).ToList());
        for (int n = 0; n < shaders.Count; n++)
        {
            if (n > 0) sb.AppendLine();
            AppendShader(sb, shaders[n], classNames[n]);
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void AppendShader(StringBuilder sb, ShaderInfo info, string className)
    {
        var shader = info.Shader;
        const string i2 = "        ", i3 = "            ", i4 = "                ";

        sb.AppendLine($"{i2}/// <summary>{Escape(shader.name)}</summary>");
        sb.AppendLine($"{i2}public static class {className}");
        sb.AppendLine($"{i2}{{");
        sb.AppendLine($"{i3}public const string ShaderName = \"{Escape(shader.name)}\";");

        var reserved = new HashSet<string> { className, "ShaderName", "Keywords", "GlobalKeywords" };
        var used = new HashSet<string>(reserved);
        int count = shader.GetPropertyCount();
        for (int p = 0; p < count; p++)
        {
            string name = shader.GetPropertyName(p);
            if (name.StartsWith("unity_")) continue;
            string id = UniqueIdentifier(ToIdentifier(name.TrimStart('_')), used);
            string desc = shader.GetPropertyDescription(p);
            var type = shader.GetPropertyType(p);
            sb.AppendLine($"{i3}/// <summary>{type}{(string.IsNullOrEmpty(desc) ? "" : "　" + Escape(desc))}</summary>");
            sb.AppendLine($"{i3}public static readonly ShaderProperty {id} = new(\"{Escape(name)}\");");
        }

        var keywords = shader.keywordSpace.keywords;
        var local = keywords.Where(k => !k.isOverridable).Select(k => k.name).Distinct().OrderBy(k => k, StringComparer.Ordinal).ToList();
        var global = info.IncludeGlobalKeywords
            ? keywords.Where(k => k.isOverridable).Select(k => k.name).Distinct().OrderBy(k => k, StringComparer.Ordinal).ToList()
            : new List<string>();
        AppendKeywords(sb, "Keywords", "材质局部关键字：ShaderManager.SetKeyword", local, i3, i4);
        AppendKeywords(sb, "GlobalKeywords", "可被全局开关的关键字：ShaderManager.SetGlobalKeyword", global, i3, i4);

        sb.AppendLine($"{i2}}}");
    }

    private static void AppendKeywords(StringBuilder sb, string className, string summary, List<string> keywords, string indent, string inner)
    {
        if (keywords.Count == 0) return;
        sb.AppendLine();
        sb.AppendLine($"{indent}/// <summary>{summary}</summary>");
        sb.AppendLine($"{indent}public static class {className}");
        sb.AppendLine($"{indent}{{");
        var used = new HashSet<string> { className };
        foreach (var keyword in keywords)
        {
            string id = UniqueIdentifier(ToIdentifier(keyword.TrimStart('_'), keepCase: true), used);
            sb.AppendLine($"{inner}public const string {id} = \"{Escape(keyword)}\";");
        }
        sb.AppendLine($"{indent}}}");
    }

    /// <summary>Shader 名 → 类名：默认取最后一段（Lit），重名时用完整路径（ParticlesUnlit）</summary>
    public static List<string> AssignClassNames(List<string> shaderNames)
    {
        var shortNames = shaderNames.Select(n => ToIdentifier(n.Split('/').Last())).ToList();
        var result = new List<string>();
        var used = new HashSet<string> { ClassName };
        for (int i = 0; i < shaderNames.Count; i++)
        {
            bool clash = shortNames.Count(s => s == shortNames[i]) > 1 || shortNames[i] == ClassName;
            string name = clash ? ToIdentifier(shaderNames[i].Replace("Universal Render Pipeline/", "")) : shortNames[i];
            result.Add(UniqueIdentifier(name, used));
        }
        return result;
    }

    /// <summary>任意字符串 → 合法 C# 标识符（PascalCase；keepCase 时保留原大小写，如关键字常量）</summary>
    public static string ToIdentifier(string raw, bool keepCase = false)
    {
        if (string.IsNullOrEmpty(raw)) return "_";
        var sb = new StringBuilder();
        bool upperNext = true;
        foreach (char c in raw)
        {
            if (char.IsLetterOrDigit(c) || (keepCase && c == '_'))
            {
                sb.Append(!keepCase && upperNext ? char.ToUpperInvariant(c) : c);
                upperNext = false;
            }
            else upperNext = true; // 空格、/、-、_ 等作为单词分隔
        }
        string id = sb.Length == 0 ? "_" : sb.ToString();
        if (char.IsDigit(id[0])) id = "_" + id;
        if (CSharpKeywords.Contains(id)) id = "@" + id;
        return id;
    }

    private static string UniqueIdentifier(string id, HashSet<string> used)
    {
        string result = id;
        for (int n = 2; used.Contains(result); n++) result = id + "_" + n;
        used.Add(result);
        return result;
    }

    private static string Escape(string s) => (s ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", " ").Replace("\r", "");

    private static readonly HashSet<string> CSharpKeywords = new HashSet<string>
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue",
        "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected",
        "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string",
        "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort",
        "using", "virtual", "void", "volatile", "while",
    };

    #endregion

    /// <summary>收集并写出 ShaderKeys.cs，返回写入的路径（失败返回 null）</summary>
    public static string Generate()
    {
        var s = HowFrameSettings.instance;
        var shaders = CollectShaders(out var warnings);
        foreach (var w in warnings) Debug.LogWarning("[ShaderKeys] " + w);
        if (shaders.Count == 0)
        {
            Debug.LogWarning("[ShaderKeys] 没有找到任何 Shader，未生成");
            return null;
        }

        string dir = HowFrameSettings.ToFullPath(s.shaderCsDir);
        Directory.CreateDirectory(dir);
        string file = Path.Combine(dir, ClassName + ".cs");
        File.WriteAllText(file, GenerateCode(shaders, string.IsNullOrWhiteSpace(s.enumNamespace) ? "HowEnum" : s.enumNamespace), new UTF8Encoding(false));
        AssetDatabase.Refresh();
        Debug.Log($"[ShaderKeys] 已为 {shaders.Count} 个 Shader 生成常量: {HowFrameSettings.ToProjectRelative(file)}");
        return file;
    }
}
